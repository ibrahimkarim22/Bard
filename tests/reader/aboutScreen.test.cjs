const assert = require('node:assert/strict');
const test = require('node:test');
const { synopsisUIHost, nodes, text } = require('../fixtures/synopsisUIHost.cjs');
const fontManifest = require('../../assets/reader-fonts/manifest.json');

const host = options => synopsisUIHost({ screen: 'screens/AboutScreen.js', ...options });
const links = h => nodes(h.render(), 'Pressable').filter(node => node.props.accessibilityRole === 'link');
const expand = h => {
  const control = h.button('Sources & credits');
  assert.ok(control, 'Sources & credits disclosure exists');
  return control.props.onPress();
};

test('About introduces the current app without implying reading alone earns a medal', () => {
  const h = host();
  assert.ok(h.button('Sources & credits'), 'Sources & credits disclosure exists');
  const content = text(h.render());
  assert.match(content, /Shakespeare, understood\./);
  assert.match(content, /38 plays.*complete texts.*original synopses.*source-backed quizzes/);
  assert.match(content, /perfect quiz result/);
  assert.match(content, /Created by Ibrahim Karim\./);
  assert.equal(nodes(h.render(), 'Text').filter(node => node.props.accessibilityRole === 'header'
    && text(node) === 'Shakespeare, understood.').length, 1);
  assert.equal(links(h).length, 0, 'the introduction is not a wall of credits');
  assert.doesNotMatch(content, /Folger Digital Texts|MIT Complete Works|generated by AI|personally written|human.verified/);
});

test('credits expand and collapse with accurate edition, editorial, artwork, font, and icon attribution', () => {
  const h = host();
  assert.equal(h.button('Sources & credits').props.accessibilityState.expanded, false);
  expand(h);
  assert.equal(h.button('Sources & credits').props.accessibilityState.expanded, true);
  const content = text(h.render());
  assert.match(content, /Project Gutenberg.*eBook 100/);
  assert.match(content, /August 24, 2025/);
  assert.match(content, /public domain in the USA/);
  assert.match(content, /Bard.*original synopses and quiz material/);
  for (const name of ['Folger Shakespeare Library', 'Rawpixel', 'Rijksmuseum', 'Wikimedia Commons', 'Smithsonian', 'Yale Center for British Art']) {
    assert.ok(content.includes(name), name);
  }
  for (const name of ['Literata', 'Source Serif 4', 'Source Sans 3', 'SIL Open Font License 1.1', 'Adobe', 'The Literata Project Authors']) {
    assert.ok(content.includes(name), name);
  }
  assert.match(content, /Font Awesome Free.*Fonticons, Inc.*CC BY 4\.0/);
  assert.doesNotMatch(content, /fetched from|Folger Digital Texts|MIT Complete Works|all (?:images|artwork).*public domain/i);
  expand(h);
  assert.equal(h.button('Sources & credits').props.accessibilityState.expanded, false);
  assert.equal(links(h).length, 0);
});

test('credit links have descriptive accessible labels and retain versioned full font notices', async () => {
  const opened = [];
  const h = host({ linking: { openURL: async url => opened.push(url) } });
  expand(h);
  const controls = links(h);
  assert.ok(controls.length >= 12);
  for (const control of controls) {
    assert.ok(control.props.accessibilityLabel);
    assert.doesNotMatch(text(control), /https?:\/\//, 'raw URLs are not link labels');
    const styles = typeof control.props.style === 'function' ? control.props.style({ pressed: false }) : control.props.style;
    assert.ok([styles].flat(Infinity).some(style => style?.minHeight >= 48), 'comfortable scalable target');
    await control.props.onPress();
  }
  assert.ok(opened.every(url => url.startsWith('https://')));
  for (const notice of fontManifest.assets.filter(asset => asset.kind === 'license')) {
    assert.ok(opened.includes(notice.url), notice.family + ' full original notice');
  }
  assert.ok(opened.includes('https://www.gutenberg.org/policy/license.html'));
  assert.ok(opened.includes('https://www.folger.edu/research/images-and-permissions/'));
});

test('a failed external link shows a concise error and a successful retry clears it', async () => {
  let fail = true;
  const h = host({ linking: { openURL: async () => { if (fail) throw Error('unavailable'); } } });
  expand(h);
  await h.button('Project Gutenberg source edition').props.onPress();
  const error = nodes(h.render(), 'Text').find(node => node.props.accessibilityRole === 'alert');
  assert.match(text(error), /Could not open this link\. Please try again\./);
  assert.equal(h.button('Sources & credits').props.accessibilityState.expanded, true);
  fail = false;
  await h.button('Project Gutenberg source edition').props.onPress();
  assert.equal(nodes(h.render(), 'Text').some(node => node.props.accessibilityRole === 'alert'), false);
});

test('a failed link at the end of credits displays its error beside that link', async () => {
  const h = host({ linking: { openURL: async () => { throw Error('unavailable'); } } });
  expand(h);
  await h.button('Creative Commons Attribution 4.0 license').props.onPress();
  const containingLinkAndError = nodes(h.render(), 'View').find(node => {
    const controls = nodes(node, 'Pressable');
    return controls.length === 1 && controls[0].props.accessibilityLabel === 'Creative Commons Attribution 4.0 license'
      && nodes(node, 'Text').some(child => child.props.accessibilityRole === 'alert');
  });
  assert.ok(containingLinkAndError, 'the error is reachable beside the activated link, not above the long credits');
});

test('closing credits or starting another link ignores an older failed opening', async () => {
  let reject;
  let wait = true;
  const h = host({ linking: { openURL: () => wait ? new Promise((_, fail) => { reject = fail; }) : Promise.resolve() } });
  expand(h);
  const oldOpening = h.button('Project Gutenberg source edition').props.onPress();
  expand(h);
  expand(h);
  reject(Error('late failure'));
  await oldOpening;
  assert.equal(nodes(h.render(), 'Text').some(node => node.props.accessibilityRole === 'alert'), false);
  const olderOpening = h.button('Project Gutenberg source edition').props.onPress();
  wait = false;
  await h.button('Project Gutenberg full license').props.onPress();
  reject(Error('older failure'));
  await olderOpening;
  assert.equal(nodes(h.render(), 'Text').some(node => node.props.accessibilityRole === 'alert'), false);
});

test('version comes only from existing Expo configuration and text keeps system scaling', () => {
  const h = host({ constants: { expoConfig: { version: '2.3.4' } } });
  assert.match(text(h.render()), /Version 2\.3\.4/);
  assert.doesNotMatch(text(host().render()), /Version/);
  expand(h);
  assert.ok(nodes(h.render(), 'Text').every(node => node.props.allowFontScaling !== false));
  assert.ok(nodes(h.render(), 'Text').every(node => node.props.numberOfLines === undefined));
  const scroll = nodes(h.render(), 'ScrollView')[0];
  assert.ok(scroll.props.contentContainerStyle.some(style => style?.paddingBottom >= 32), 'final content remains reachable');
  assert.ok(nodes(h.render(), 'Text').some(node => String(node.props.style?.flat(Infinity).find(style => style?.fontFamily)?.fontFamily).includes('BardSynopsisSerif')));
});
